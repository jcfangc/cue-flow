// 文件职责：将已检查的协议组装为 Rust 模块源码，包括消息、Transport API 和双方状态接口。
// Rust 字段类型先由 schema.go 降级，Rust 标识符映射由 names.go 负责。
package rust

import (
	"bytes"
	"fmt"
	"strconv"

	"github.com/jcfangc/cue-flow/internal/compiler"
)

func Generate(p *Protocol) (string, error) {
	if p == nil {
		return "", fmt.Errorf("protocol is empty")
	}
	if err := compiler.Check(p); err != nil {
		return "", err
	}
	names, err := lowerRustNames(p)
	if err != nil {
		return "", err
	}
	var out bytes.Buffer
	writePrelude(&out)
	if err := writeMessages(&out, names.messages, names); err != nil {
		return "", err
	}
	writeEndpoint(&out, "server", "ServerSession", p, names, false)
	writeEndpoint(&out, "client", "ClientSession", p, names, true)
	return out.String(), nil
}

func writePrelude(out *bytes.Buffer) {
	out.WriteString(`// Generated by cueflow. Do not edit by hand.
#[derive(Debug)]
pub enum ValidationError {
    Empty(&'static str),
    Pattern { field: &'static str, pattern: &'static str },
    PatternCompile(&'static str),
    Length { field: &'static str, min: Option<usize>, max: Option<usize> },
    IntegerRange { field: &'static str, min: i64, max: i64 },
}

#[derive(Debug)]
pub enum ProtocolError<E> {
    Transport(E),
    Validation(ValidationError),
}

/// A transport-level event received for the current logical session.
pub enum Inbound<M> {
    Message(M),
    Close,
}

/// Result of receiving a protocol message or the peer's logical Close.
pub enum ReceiveOutcome<M, S> {
    Message { message: M, session: S },
    Closed,
}

fn deserialize_present<'de, D, T>(deserializer: D) -> std::result::Result<Option<T>, D::Error>
where
    D: serde::Deserializer<'de>,
    T: serde::Deserialize<'de>,
{
    <T as serde::Deserialize>::deserialize(deserializer).map(Some)
}

/// Runtime boundary. Implementations choose the wire format and scheduling model.
#[allow(async_fn_in_trait)]
pub trait Transport: Send {
    type Error: Send;

    async fn send<M: serde::Serialize + Sync>(&mut self, message_id: &'static str, message: &M) -> std::result::Result<(), Self::Error>;
    async fn recv<M: serde::de::DeserializeOwned + Send>(&mut self, message_id: &'static str) -> std::result::Result<Inbound<M>, Self::Error>;
    /// Send a logical Close event. This does not imply closing the transport connection.
    async fn send_close(&mut self) -> std::result::Result<(), Self::Error>;
    /// Wait for logical Close while preserving unrelated business messages for recv.
    async fn recv_close(&mut self) -> std::result::Result<(), Self::Error>;
}

`)
}

func writeMessages(out *bytes.Buffer, messages []rustMessage, names *rustNames) error {
	out.WriteString("pub mod messages {\n\n")
	for _, message := range messages {
		writeMessage(out, message, names)
	}
	out.WriteString("}\n\n")
	return nil
}

func writeMessage(out *bytes.Buffer, message rustMessage, names *rustNames) {
	typeName := names.messageTypes[message.ID]
	fmt.Fprintf(out, "    #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n    #[serde(deny_unknown_fields)]\n    pub struct %s {\n", typeName)
	for _, field := range message.Fields {
		writeMessageField(out, field, names.fieldNames[message.ID][field.Name], names.fieldTypes[message.ID][field.Name])
	}
	out.WriteString("    }\n\n")
	fmt.Fprintf(out, "    impl %s {\n        pub fn validate(&self) -> std::result::Result<(), super::ValidationError> {\n", typeName)
	for _, field := range message.Fields {
		writeFieldValidation(out, field, names.fieldNames[message.ID][field.Name])
	}
	out.WriteString("            Ok(())\n        }\n    }\n\n")
}

func writeMessageField(out *bytes.Buffer, field rustMessageField, fieldName, fieldType string) {
	typ := fieldType
	if !field.Required {
		typ = "Option<" + typ + ">"
	}
	if field.Required {
		fmt.Fprintf(out, "        #[serde(rename = %s)]\n        pub %s: %s,\n", strconv.Quote(field.Name), fieldName, typ)
		return
	}
	// Optional CUE fields should be omitted on the wire when absent.
	fmt.Fprintf(out, "        #[serde(rename = %s, default, deserialize_with = \"super::deserialize_present\", skip_serializing_if = \"Option::is_none\")]\n        pub %s: %s,\n", strconv.Quote(field.Name), fieldName, typ)
}

func writeFieldValidation(out *bytes.Buffer, field rustMessageField, fieldName string) {
	if !field.RejectEmpty && field.Pattern == "" && field.MinLength == nil && field.MaxLength == nil && field.MinInt == nil {
		return
	}
	access := "self." + fieldName
	if !field.Required {
		fmt.Fprintf(out, "            if let Some(value) = %s.as_ref() {\n", access)
		access = "value"
	}
	writeStringValidation(out, field, access)
	writeIntegerValidation(out, field, access)
	if !field.Required {
		out.WriteString("            }\n")
	}
}

func writeStringValidation(out *bytes.Buffer, field rustMessageField, access string) {
	if field.RejectEmpty {
		fmt.Fprintf(out, "                if %s.is_empty() { return Err(super::ValidationError::Empty(%s)); }\n", access, strconv.Quote(field.Name))
	}
	if field.Pattern != "" {
		fmt.Fprintf(out, "                let pattern = regex::Regex::new(%s).map_err(|_| super::ValidationError::PatternCompile(%s))?;\n                if !pattern.is_match(&%s) { return Err(super::ValidationError::Pattern { field: %s, pattern: %s }); }\n",
			strconv.Quote(field.Pattern), strconv.Quote(field.Name), access, strconv.Quote(field.Name), strconv.Quote(field.Pattern))
	}
	if field.MinLength != nil || field.MaxLength != nil {
		min := "None"
		max := "None"
		if field.MinLength != nil {
			min = fmt.Sprintf("Some(%d)", *field.MinLength)
		}
		if field.MaxLength != nil {
			max = fmt.Sprintf("Some(%d)", *field.MaxLength)
		}
		fmt.Fprintf(out, "                let length = %s.chars().count();\n                if %s || %s { return Err(super::ValidationError::Length { field: %s, min: %s, max: %s }); }\n",
			access,
			lengthComparison(access, field.MinLength, true),
			lengthComparison(access, field.MaxLength, false),
			strconv.Quote(field.Name), min, max)
	}
}

func writeIntegerValidation(out *bytes.Buffer, field rustMessageField, access string) {
	if field.MinInt == nil || field.MaxInt == nil {
		return
	}
	numericAccess := access
	if !field.Required {
		numericAccess = "*" + access
	}
	fmt.Fprintf(out, "                if %s < %d || %s > %d { return Err(super::ValidationError::IntegerRange { field: %s, min: %d, max: %d }); }\n",
		numericAccess, *field.MinInt, numericAccess, *field.MaxInt, strconv.Quote(field.Name), *field.MinInt, *field.MaxInt)
}

func lengthComparison(access string, bound *int64, minimum bool) string {
	if bound == nil {
		return "false"
	}
	if minimum {
		return fmt.Sprintf("length < %d", *bound)
	}
	return fmt.Sprintf("length > %d", *bound)
}

func writeEndpoint(out *bytes.Buffer, module, sessionName string, p *Protocol, names *rustNames, dual bool) {
	fmt.Fprintf(out, "pub mod %s {\n    use super::{messages, Inbound, ProtocolError, ReceiveOutcome, Transport};\n    use std::marker::PhantomData;\n\n", module)
	for _, state := range p.States {
		fmt.Fprintf(out, "    pub struct %s;\n", names.stateTypes[state.ID])
	}
	fmt.Fprintf(out, "\n    pub struct %s<T: Transport, S> {\n        transport: T,\n        _state: PhantomData<S>,\n    }\n\n", sessionName)
	fmt.Fprintf(out, "    impl<T: Transport, S> %s<T, S> {\n        fn transition<N>(self) -> %s<T, N> {\n            %s { transport: self.transport, _state: PhantomData }\n        }\n    }\n\n", sessionName, sessionName, sessionName)
	fmt.Fprintf(out, "    impl<T: Transport> %s<T, %s> {\n        pub fn new(transport: T) -> Self {\n            Self { transport, _state: PhantomData }\n        }\n    }\n\n", sessionName, names.stateTypes[p.Initial])

	for _, state := range p.States {
		if state.Terminal {
			continue
		}
		writeStateMethods(out, sessionName, state, names, dual)
	}
	if dual {
		out.WriteString("    // Client transitions are derived by swapping server send and recv.\n")
	} else {
		out.WriteString("    // This module is generated from the server-local protocol.\n")
	}
	out.WriteString("}\n\n")
}

func writeStateMethods(out *bytes.Buffer, sessionName string, state State, names *rustNames, dual bool) {
	fmt.Fprintf(out, "    impl<T: Transport> %s<T, %s> {\n", sessionName, names.stateTypes[state.ID])
	for _, transition := range state.Sends {
		if dual {
			writeRecvMethod(out, sessionName, transition, names.messageTypes[transition.MessageID], names.clientRecvMethods[state.ID][transition.MessageID], names.stateTypes[transition.Target])
			continue
		}
		writeSendMethod(out, sessionName, transition, names.messageTypes[transition.MessageID], names.serverSendMethods[state.ID][transition.MessageID], names.stateTypes[transition.Target])
	}
	for _, transition := range state.Receives {
		if dual {
			writeSendMethod(out, sessionName, transition, names.messageTypes[transition.MessageID], names.clientSendMethods[state.ID][transition.MessageID], names.stateTypes[transition.Target])
			continue
		}
		writeRecvMethod(out, sessionName, transition, names.messageTypes[transition.MessageID], names.serverRecvMethods[state.ID][transition.MessageID], names.stateTypes[transition.Target])
	}
	fmt.Fprintf(out, "        pub async fn close(mut self) -> std::result::Result<(), ProtocolError<T::Error>> {\n            self.transport.send_close().await.map_err(ProtocolError::Transport)\n        }\n")
	fmt.Fprintf(out, "        pub async fn recv_close(mut self) -> std::result::Result<(), ProtocolError<T::Error>> {\n            self.transport.recv_close().await.map_err(ProtocolError::Transport)\n        }\n")
	out.WriteString("    }\n\n")
}

func writeSendMethod(out *bytes.Buffer, sessionName string, transition Transition, messageType, method, targetType string) {
	fmt.Fprintf(out, "        pub async fn %s(mut self, message: messages::%s) -> std::result::Result<%s<T, %s>, ProtocolError<T::Error>> {\n",
		method, messageType, sessionName, targetType)
	out.WriteString("            message.validate().map_err(ProtocolError::Validation)?;\n")
	fmt.Fprintf(out, "            self.transport.send(%s, &message).await.map_err(ProtocolError::Transport)?;\n", strconv.Quote(transition.MessageID))
	fmt.Fprintf(out, "            Ok(self.transition::<%s>())\n        }\n", targetType)
}

func writeRecvMethod(out *bytes.Buffer, sessionName string, transition Transition, messageType, method, targetType string) {
	fmt.Fprintf(out, "        pub async fn %s(mut self) -> std::result::Result<ReceiveOutcome<messages::%s, %s<T, %s>>, ProtocolError<T::Error>> {\n",
		method, messageType, sessionName, targetType)
	fmt.Fprintf(out, "            let event = self.transport.recv::<messages::%s>(%s).await.map_err(ProtocolError::Transport)?;\n", messageType, strconv.Quote(transition.MessageID))
	out.WriteString("            match event {\n                Inbound::Close => Ok(ReceiveOutcome::Closed),\n                Inbound::Message(message) => {\n                    message.validate().map_err(ProtocolError::Validation)?;\n")
	fmt.Fprintf(out, "                    let session = self.transition::<%s>();\n                    Ok(ReceiveOutcome::Message { message, session })\n                }\n            }\n        }\n", targetType)
}
