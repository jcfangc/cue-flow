// 文件职责：将已检查的协议降级为完整的 Python 模块源码。
// 消息模型由 messages.go 生成，名称映射由 names.go 负责，端点状态方法在本文件组装。
package python

import (
	"bytes"
	"fmt"
	"strconv"

	"github.com/jcfangc/cue-flow/internal/compiler"
)

func Generate(protocol *Protocol) (string, error) {
	if protocol == nil {
		return "", fmt.Errorf("protocol is empty")
	}
	if err := compiler.Check(protocol); err != nil {
		return "", err
	}
	names, err := lowerPythonNames(protocol)
	if err != nil {
		return "", err
	}
	var output bytes.Buffer
	writePrelude(&output)
	if err := writeMessages(&output, names); err != nil {
		return "", err
	}
	writeEndpoints(&output, protocol, names)
	return output.String(), nil
}

func writePrelude(output *bytes.Buffer) {
	output.WriteString(`"""Generated by cueflow. Do not edit by hand."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Generic, Protocol, TypeVar

from pydantic import BaseModel, ConfigDict, Field, StrictBool, StrictInt, StrictStr
from pydantic import ValidationError as PydanticValidationError
from pydantic import field_validator


class ProtocolError(Exception):
    """Base error for generated protocol APIs."""


class TransportFailure(ProtocolError):
    """The transport failed while sending or receiving a protocol event."""


class MessageValidationFailure(ProtocolError):
    """A received or sent message violates its generated model."""


class UnexpectedMessage(ProtocolError):
    """The transport returned a message ID not expected in this state."""


@dataclass(frozen=True)
class InboundMessage:
    message_id: str
    payload: object


@dataclass(frozen=True)
class InboundClose:
    pass


Inbound = InboundMessage | InboundClose


class Transport(Protocol):
    async def send(self, message_id: str, message: BaseModel) -> None: ...
    async def recv(self, message_id: str) -> Inbound: ...
    async def send_close(self) -> None: ...
    async def recv_close(self) -> None: ...


MessageT = TypeVar("MessageT", bound=BaseModel)
StateT = TypeVar("StateT")


@dataclass(frozen=True)
class Received(Generic[MessageT, StateT]):
    message: MessageT
    session: StateT


@dataclass(frozen=True)
class Closed:
    pass


class _Session:
    def __init__(self, transport: Transport) -> None:
        self._transport: Transport | None = transport

    def _take_transport(self) -> Transport:
        transport = self._transport
        if transport is None:
            raise ProtocolError("session state was already consumed")
        self._transport = None
        return transport

`)
}

func writeEndpoints(output *bytes.Buffer, protocol *Protocol, names *pythonNames) {
	writeEndpoint(output, "server", protocol, names)
	writeEndpoint(output, "client", protocol, names)
}

func writeEndpoint(output *bytes.Buffer, endpoint string, protocol *Protocol, names *pythonNames) {
	for _, state := range protocol.States {
		className := names.stateClasses[endpoint][state.ID]
		fmt.Fprintf(output, "class %s(_Session):\n", className)
		if state.Terminal {
			output.WriteString("    pass\n\n")
			continue
		}
		writeStateMethods(output, endpoint, state, names)
		writeCloseMethods(output)
		output.WriteByte('\n')
	}
}

func writeStateMethods(output *bytes.Buffer, endpoint string, state State, names *pythonNames) {
	if endpoint == "server" {
		for _, transition := range state.Sends {
			writeSendMethod(output, endpoint, state, transition, names)
		}
		for _, transition := range state.Receives {
			writeReceiveMethod(output, endpoint, state, transition, names)
		}
		return
	}
	for _, transition := range state.Sends {
		writeReceiveMethod(output, endpoint, state, transition, names)
	}
	for _, transition := range state.Receives {
		writeSendMethod(output, endpoint, state, transition, names)
	}
}

func writeSendMethod(output *bytes.Buffer, endpoint string, state State, transition Transition, names *pythonNames) {
	method := names.serverSend[state.ID][transition.MessageID]
	target := names.stateClasses[endpoint][transition.Target]
	if endpoint == "client" {
		method = names.clientSend[state.ID][transition.MessageID]
	}
	messageType := names.messageClasses[transition.MessageID]
	fmt.Fprintf(output, "    async def %s(self, message: %s) -> %s:\n", method, messageType, target)
	fmt.Fprintf(output, "        try:\n            validated = %s.model_validate(message.model_dump(by_alias=True, exclude_unset=True))\n", messageType)
	output.WriteString("        except PydanticValidationError as error:\n            raise MessageValidationFailure(str(error)) from error\n")
	output.WriteString("        transport = self._take_transport()\n")
	fmt.Fprintf(output, "        try:\n            await transport.send(%s, validated)\n", strconv.Quote(transition.MessageID))
	output.WriteString("        except Exception as error:\n            raise TransportFailure(str(error)) from error\n")
	fmt.Fprintf(output, "        return %s(transport)\n\n", target)
}

func writeReceiveMethod(output *bytes.Buffer, endpoint string, state State, transition Transition, names *pythonNames) {
	method := names.serverReceive[state.ID][transition.MessageID]
	target := names.stateClasses[endpoint][transition.Target]
	if endpoint == "client" {
		method = names.clientReceive[state.ID][transition.MessageID]
	}
	messageType := names.messageClasses[transition.MessageID]
	fmt.Fprintf(output, "    async def %s(self) -> Received[%s, %s] | Closed:\n", method, messageType, target)
	output.WriteString("        transport = self._take_transport()\n")
	fmt.Fprintf(output, "        try:\n            inbound = await transport.recv(%s)\n", strconv.Quote(transition.MessageID))
	output.WriteString("        except Exception as error:\n            raise TransportFailure(str(error)) from error\n")
	output.WriteString("        if isinstance(inbound, InboundClose):\n            return Closed()\n")
	fmt.Fprintf(output, "        if inbound.message_id != %s:\n            raise UnexpectedMessage(\"expected \" + %s + \", received \" + inbound.message_id)\n", strconv.Quote(transition.MessageID), strconv.Quote(transition.MessageID))
	fmt.Fprintf(output, "        try:\n            message = %s.model_validate(inbound.payload)\n", messageType)
	output.WriteString("        except PydanticValidationError as error:\n            raise MessageValidationFailure(str(error)) from error\n")
	fmt.Fprintf(output, "        return Received(message, %s(transport))\n\n", target)
}

func writeCloseMethods(output *bytes.Buffer) {
	output.WriteString(`    async def close(self) -> None:
        transport = self._take_transport()
        try:
            await transport.send_close()
        except Exception as error:
            raise TransportFailure(str(error)) from error

    async def recv_close(self) -> None:
        transport = self._take_transport()
        try:
            await transport.recv_close()
        except Exception as error:
            raise TransportFailure(str(error)) from error
`)
}
